CREATE TABLE bookings (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          customer_id BIGINT NOT NULL,
                          vehicle_id BIGINT NOT NULL,
                          driver_id BIGINT,
                          booking_reference VARCHAR(50),
                          customer_phone_number VARCHAR(20) NOT NULL,
                          trip_type VARCHAR(30) NOT NULL,
                          passenger_count INT NOT NULL,
                          pickup_location VARCHAR(150) NOT NULL,
                          dropoff_location VARCHAR(150) NOT NULL,
                          start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                          end_date_time TIMESTAMP WITHOUT TIME ZONE,
                          price_per_km INT NOT NULL,
                          status VARCHAR(30) DEFAULT 'CONFIRMED' NOT NULL,
                          notes TEXT,
                          rejection_reason TEXT,
                          created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                          updated_at TIMESTAMP WITHOUT TIME ZONE,
                          cancelled_at TIMESTAMP WITHOUT TIME ZONE,
                          CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id)
                              REFERENCES users (id) ON DELETE RESTRICT,
                          CONSTRAINT fk_bookings_vehicle FOREIGN KEY (vehicle_id)
                              REFERENCES vehicles (id) ON DELETE RESTRICT,
                          CONSTRAINT fk_bookings_driver FOREIGN KEY (driver_id)
                              REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE trip (
                      trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      booking_id BIGINT NOT NULL UNIQUE,
                      started_at TIMESTAMP WITHOUT TIME ZONE,
                      completed_at TIMESTAMP WITHOUT TIME ZONE,
                      actual_start_location VARCHAR(255),
                      actual_end_location VARCHAR(255),
                      status VARCHAR(30) NOT NULL,
                      CONSTRAINT fk_trips_booking FOREIGN KEY (booking_id)
                          REFERENCES bookings (id) ON DELETE CASCADE
